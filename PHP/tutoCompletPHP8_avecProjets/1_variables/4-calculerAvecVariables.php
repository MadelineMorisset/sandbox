$nombre1 = 30;
$nombre2 = 2;
// Réaliser une addition
$somme = $nombre1 + $nombre2;
echo "Somme de " . $nombre1 . " et " . $nombre2 . " = " . $somme . "<br/>";

// Réaliser une soustracion
$difference = $nombre1 - $nombre2;
echo "Différence de " . $nombre1 . " et " . $nombre2 . " = " . $difference . "<br/>";

// Réaliser une multiplication
$produit = $nombre1 * $nombre2;
echo "Produit de " . $nombre1 . " et " . $nombre2 . " = " . $produit . "<br/>";

// Réaliser une division
$quotient = $nombre1 / $nombre2;
echo "Quotient de " . $nombre1 . " et " . $nombre2 . " = " . $quotient . "<br/>";

// Réaliser une modulo (reste d'une division)
$reste = $nombre1 % $nombre2;
echo "Reste de " . $nombre1 . " et " . $nombre2 . " = " . $reste . "<br/>";